#!/usr/bin/env node
/**
 * monitor-podcast-feed.mjs — runtime health check for the failurefirst.org podcast feeds.
 *
 * COMPLEMENTS (does not duplicate) the deploy-time build gate verify-podcast-build.mjs.
 * The build gate proves the EMITTED feed is internally consistent with its caches at
 * generation time. This monitor probes the LIVE SERVING LAYER for failures a green build
 * can never see, and which appear only later with zero redeploys:
 *   - enclosure URL 404 / object deleted or replaced out-of-band
 *   - Content-Type (MIME) drift on the CDN
 *   - lost byte-range (206) support (breaks podcast-client seeking with intact bytes)
 *   - advertised length no longer matching the served object
 *
 * Contract (operator-specified 2026-07-22):
 *   1. A 206 response is AUTHORITATIVE for range support. Do NOT require the
 *      `Accept-Ranges` header — servers may omit it while honoring ranges.
 *   2. Compare the feed's advertised length against the `Content-Range` TOTAL
 *      (`bytes 0-11/TOTAL`), never the partial response's `Content-Length` (always 12).
 *   3. KNOWN CDN QUIRK: `.m4a` audio objects (declared audio/mp4) are SERVED with
 *      Content-Type video/mp4. So MIME cannot distinguish audio from video and must not
 *      be asserted strictly. `ftyp` box validation is the authoritative integrity check
 *      (required for every enclosure); served MIME is tolerated across the audio/* family
 *      (audio/mp4, audio/x-m4a, audio/mp4a-latm, ...) plus video/mp4, and only a genuinely
 *      NON-media type (application/octet-stream, an HTML error page, ...) raises an alarm.
 *   4. One `Range: bytes=0-11` request per DEDUPLICATED enclosure verifies availability,
 *      206 support, total size, MIME, and ftyp in a single round-trip (no separate HEAD).
 *   5. Bounded concurrency, per-request timeout, retries; a URL is a FAILURE only after
 *      it fails every attempt (alert only on persistent failure).
 *
 * Exit code: 0 = all healthy; 1 = at least one persistent failure (drives the CI alert);
 *            2 = could not fetch a feed (monitor itself could not run).
 *
 * Usage:
 *   node monitor-podcast-feed.mjs                 # check all unique enclosures on prod
 *   node monitor-podcast-feed.mjs --limit 20      # check first 20 (smoke test)
 *   node monitor-podcast-feed.mjs --feeds a,b     # override feed URLs (comma-separated)
 */

const FEEDS = [
  'https://failurefirst.org/audio/feed.xml',
  'https://failurefirst.org/audio/podcast.xml',
];
const CONCURRENCY = 8;
const RETRIES = 3;
const TIMEOUT_MS = 20_000;
const RETRY_BASE_MS = 1_000;
// Served Content-Type acceptance predicate. ftyp is the real integrity anchor (an HTML
// error page or truncated blob fails it), so MIME only needs to catch a media object
// served under a NON-media type that breaks client playback. The CDN legitimately serves
// .m4a audio under several MPEG-4 synonyms (audio/mp4, audio/x-m4a, audio/mp4a-latm) and,
// per the known quirk, as video/mp4 — so accept the whole audio/* family plus video/mp4,
// and alarm only on genuinely non-media types (application/octet-stream, text/html, ...).
const isAcceptableMediaMime = (ct) => ct.startsWith('audio/') || ct === 'video/mp4';

// ---- args ----
const argv = process.argv.slice(2);
function argValue(flag) {
  const i = argv.indexOf(flag);
  return i >= 0 && i + 1 < argv.length ? argv[i + 1] : null;
}
const limit = argValue('--limit') ? Number(argValue('--limit')) : null;
const feeds = argValue('--feeds') ? argValue('--feeds').split(',').map((s) => s.trim()) : FEEDS;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchWithTimeout(url, opts = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    return await fetch(url, { ...opts, signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

async function withRetry(fn) {
  let lastErr;
  for (let attempt = 1; attempt <= RETRIES; attempt++) {
    try {
      return await fn(attempt);
    } catch (e) {
      lastErr = e;
      if (attempt < RETRIES) await sleep(RETRY_BASE_MS * attempt);
    }
  }
  throw lastErr;
}

async function fetchFeed(url) {
  const res = await withRetry(async () => {
    const r = await fetchWithTimeout(url);
    if (!r.ok) throw new Error(`feed ${url} -> HTTP ${r.status}`);
    return r;
  });
  return res.text();
}

// Order-agnostic enclosure attribute extraction. The feed is generated by us, but never
// assume attribute order (url/type/length appear in varying orders across emitters).
function parseEnclosures(xml) {
  const out = [];
  const encRe = /<enclosure\b([^>]*?)\/?>/g;
  const attrRe = /([\w:-]+)\s*=\s*"([^"]*)"/g;
  let m;
  while ((m = encRe.exec(xml)) !== null) {
    const attrs = {};
    let a;
    while ((a = attrRe.exec(m[1])) !== null) attrs[a[1]] = a[2];
    if (attrs.url) out.push({ url: attrs.url, type: attrs.type, length: Number(attrs.length) });
  }
  return out;
}

// Dedupe across both feeds. Same URL in Apple+Spotify must agree on length/type; a
// disagreement is itself an integrity defect, surfaced as a failure.
function dedupe(enclosures) {
  const byUrl = new Map();
  const conflicts = [];
  for (const e of enclosures) {
    const prev = byUrl.get(e.url);
    if (!prev) {
      byUrl.set(e.url, e);
    } else if (prev.length !== e.length || prev.type !== e.type) {
      conflicts.push({
        url: e.url,
        reason: `feed metadata conflict: ${prev.type}/${prev.length} vs ${e.type}/${e.length}`,
      });
    }
  }
  return { unique: [...byUrl.values()], conflicts };
}

function parseContentRangeTotal(header) {
  // "bytes 0-11/43459826" -> 43459826 ; "*" total is unknown -> null
  const m = /\/(\d+)\s*$/.exec(header || '');
  return m ? Number(m[1]) : null;
}

// bytes 4..7 of an ISO-BMFF file spell "ftyp"; bytes 8..11 are the major brand.
function ftypBrand(bytes) {
  if (!bytes || bytes.length < 12) return null;
  const box = String.fromCharCode(bytes[4], bytes[5], bytes[6], bytes[7]);
  if (box !== 'ftyp') return null;
  return String.fromCharCode(bytes[8], bytes[9], bytes[10], bytes[11]).trim();
}

async function checkEnclosure(enc) {
  try {
    const brand = await withRetry(async () => {
      const res = await fetchWithTimeout(enc.url, { headers: { Range: 'bytes=0-11' } });

      // Contract #1: 206 is authoritative. A 200 means the server ignored the Range and
      // would stream the whole object — do NOT read the body (avoid a full download);
      // treat as a range-support failure.
      if (res.status !== 206) {
        throw new Error(`expected 206, got ${res.status}`);
      }

      // Contract #2: total size comes from Content-Range, not the partial Content-Length.
      const total = parseContentRangeTotal(res.headers.get('content-range'));
      if (total === null) throw new Error(`unparseable Content-Range: ${res.headers.get('content-range')}`);
      if (total !== enc.length) throw new Error(`served total ${total} != feed length ${enc.length}`);

      const bytes = new Uint8Array(await res.arrayBuffer());
      const b = ftypBrand(bytes);
      const ct = (res.headers.get('content-type') || '').split(';')[0].trim();

      // Contract #3: ftyp is the authoritative integrity check (always required). The CDN
      // serves .m4a audio as video/mp4, so served MIME cannot be strictly asserted — it is
      // only required to stay within the mp4 family; anything else is genuine drift.
      if (b === null) throw new Error(`missing/invalid ftyp box (MIME=${ct || 'none'})`);
      if (!isAcceptableMediaMime(ct)) throw new Error(`non-media MIME drift: ${ct || '(none)'}`);
      return b;
    });
    return { url: enc.url, type: enc.type, ok: true, brand };
  } catch (e) {
    return { url: enc.url, type: enc.type, ok: false, reason: e.message };
  }
}

async function pool(items, worker, concurrency) {
  const results = new Array(items.length);
  let next = 0;
  async function run() {
    while (true) {
      const idx = next++;
      if (idx >= items.length) return;
      results[idx] = await worker(items[idx], idx);
    }
  }
  await Promise.all(
    Array.from({ length: Math.min(concurrency, items.length) }, run),
  );
  return results;
}

async function main() {
  let all = [];
  try {
    const xmls = await Promise.all(feeds.map(fetchFeed));
    all = xmls.flatMap(parseEnclosures);
  } catch (e) {
    console.error(`FATAL: could not fetch a feed — ${e.message}`);
    process.exit(2);
  }
  if (all.length === 0) {
    console.error('FATAL: parsed 0 enclosures from feeds (format change?)');
    process.exit(2);
  }

  const { unique, conflicts } = dedupe(all);
  let toCheck = unique;
  let sampled = false;
  if (limit && limit < unique.length) {
    toCheck = unique.slice(0, limit);
    sampled = true;
  }

  const checked = await pool(toCheck, checkEnclosure, CONCURRENCY);
  const failures = [...conflicts, ...checked.filter((r) => !r.ok)];

  const summary = {
    feeds,
    totalEnclosures: all.length,
    uniqueEnclosures: unique.length,
    checked: toCheck.length,
    sampled: sampled ? `first ${limit} of ${unique.length}` : false,
    healthy: checked.filter((r) => r.ok).length,
    failures: failures.length,
    failureDetail: failures.map((f) => ({ url: f.url, reason: f.reason })),
  };
  console.log(JSON.stringify(summary, null, 2));

  if (sampled) {
    console.error(`NOTE: sampled run — ${unique.length - toCheck.length} enclosures NOT checked.`);
  }
  process.exit(failures.length > 0 ? 1 : 0);
}

main();
